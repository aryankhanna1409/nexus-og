"""Deterministic offline provider used when no LLM API key is configured.

`tool_call` delegates to the rule-based RCA investigator; `generate` returns a
deterministic summary built only from the JSON context it is given (used by
the reporting engine). Outputs are labelled as coming from the mock provider.
"""

from __future__ import annotations

import json
from typing import Any

from app.llm.base import LLMProvider, LLMResponse, Message, ToolSpec, UserMessage

CONTEXT_JSON_MARKER = "REPORT_CONTEXT_JSON:"


class MockProvider(LLMProvider):
    name = "mock"
    model = "mock-deterministic-v1"

    def __init__(self, reason: str = "LLM_PROVIDER=mock") -> None:
        self.reason = reason

    def tool_call(self, system: str, messages: list[Message], tools: list[ToolSpec], *,
                  max_tokens: int = 16000) -> LLMResponse:
        from app.rca.mock_investigator import next_turn

        allowed = {t.name for t in tools}
        text, calls = next_turn(messages)
        calls = [c for c in calls if c.name in allowed]
        return LLMResponse(text=text, tool_calls=tuple(calls),
                           stop_reason="tool_use" if calls else "end_turn", model=self.model,
                           provider=self.name)

    def generate(self, system: str, messages: list[Message], *, max_tokens: int = 4096) -> LLMResponse:
        prompt = next((m.text for m in reversed(messages) if isinstance(m, UserMessage)), "")
        context: dict[str, Any] = {}
        if CONTEXT_JSON_MARKER in prompt:
            context = json.loads(prompt.split(CONTEXT_JSON_MARKER, 1)[1])
        text = template_summary(context)
        return LLMResponse(text=text, tool_calls=(), stop_reason="end_turn", model=self.model,
                           provider=self.name)


def template_summary(context: dict[str, Any]) -> str:
    """Template summary: every number comes from `context`, nothing is invented."""
    if not context:
        return "No context was provided; no summary generated (deterministic mock provider)."
    parts = [f"Incident {context.get('incident_id', '?')} ({context.get('severity', '?')})"]
    if context.get("window"):
        parts.append(f"degraded service from {context['window']}")
    sentence = " ".join(parts) + "."
    findings = context.get("key_findings", [])
    if findings:
        sentence += " Key changes: " + "; ".join(findings[:4]) + "."
    if context.get("root_cause"):
        sentence += (f" Most likely cause (hypothesis, confidence {context.get('confidence', 0):.0%}): "
                     f"{context['root_cause']}")
    return sentence + " [generated by the deterministic mock provider]"

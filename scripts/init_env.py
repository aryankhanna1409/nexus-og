#!/usr/bin/env python3
"""Create a local .env with generated credentials for the Docker stack.

Refuses to overwrite an existing .env. Raw API tokens are written to
.aegis-tokens (mode 600, git-ignored) and printed once; only their SHA-256
hashes go into .env.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import secrets
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ROLES = ("viewer", "operator", "approver", "admin")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--env-file", type=Path, default=REPO_ROOT / ".env")
    parser.add_argument("--tokens-file", type=Path, default=REPO_ROOT / ".aegis-tokens")
    args = parser.parse_args(argv)
    env_path, tokens_path = args.env_file, args.tokens_file
    if env_path.exists():
        print(f"{env_path} already exists; not overwriting.", file=sys.stderr)
        return 1
    tokens = {role: secrets.token_urlsafe(32) for role in ROLES}
    spec = ",".join(f"local-{r}:{r}:{hashlib.sha256(t.encode()).hexdigest()}" for r, t in tokens.items())
    template = (REPO_ROOT / ".env.example").read_text()
    lines = []
    for line in template.splitlines():
        if line.startswith("AEGIS_API_TOKENS="):
            line = f"AEGIS_API_TOKENS={spec}"
        lines.append(line)
    lines += ["", "# Generated by scripts/init_env.py for the Docker stack (local use only).",
              f"POSTGRES_PASSWORD={secrets.token_urlsafe(24)}"]
    env_path.write_text("\n".join(lines) + "\n")
    os.chmod(env_path, 0o600)
    tokens_path.write_text("".join(f"{role}={token}\n" for role, token in tokens.items()))
    os.chmod(tokens_path, 0o600)
    print(f"Wrote {env_path} and {tokens_path} (raw tokens; keep private).")
    for role, token in tokens.items():
        print(f"  {role:9s} {token}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
